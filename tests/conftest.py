"""Shared fixtures.

The board here is hand-built rather than generated by `board.random_board`, so
every test can name a specific component and know its package, position and
rotation. Parts are spaced 5.5 mm apart, which is wider than the largest
footprint the renderer draws (TANT-A, ~4.5 mm with margin), so no component
blits over its neighbour and a measurement can only be reading its own part.

Rendering is the slow step, so the golden stacks and the fitted golden model are
session-scoped and shared across the whole suite.
"""
from __future__ import annotations

import os

import numpy as np
import pytest

from aoi import board as B
from aoi import roi, rules, synth

# the photo app must not build goldens on background threads while tests run
os.environ.setdefault("AOI_WARM_GOLDENS", "0")

N_GOLDEN = 5


@pytest.fixture(scope="session")
def brd() -> B.Board:
    """A small board carrying every package family the library defines."""
    comps = [
        B.Component("R1", "0402", x=4.0, y=4.0, rot=0.0),
        B.Component("R2", "0402", x=9.5, y=4.0, rot=90.0),
        B.Component("R3", "0603", x=15.0, y=4.0, rot=0.0),
        B.Component("R4", "0603", x=4.0, y=9.5, rot=180.0),
        B.Component("R5", "0805", x=9.5, y=9.5, rot=0.0),
        B.Component("D1", "SOD-123", x=15.0, y=9.5, rot=0.0),
        B.Component("C1", "TANT-A", x=5.0, y=15.0, rot=0.0),
        B.Component("R6", "0402", x=11.0, y=15.0, rot=0.0),
        B.Component("D2", "SOD-123", x=16.0, y=15.0, rot=180.0),
    ]
    fids = [(2.0, 2.0), (20.0, 2.0), (20.0, 18.0)]
    return B.Board("TEST-1", 22.0, 20.0, comps, fids)


@pytest.fixture(scope="session")
def golden_stacks(brd: B.Board) -> list[np.ndarray]:
    """Known-good scans. Default placement scatter is left on so the golden
    band statistics get a real standard deviation to threshold against."""
    return [synth.render(brd, opts=synth.RenderOpts(seed=200 + i))
            for i in range(N_GOLDEN)]


@pytest.fixture(scope="session")
def golden(golden_stacks: list[np.ndarray], brd: B.Board) -> rules.Golden:
    return rules.fit_golden(golden_stacks, brd)


@pytest.fixture(scope="session")
def good_patches(golden_stacks: list[np.ndarray], brd: B.Board) -> dict[str, np.ndarray]:
    """Model-input patches from the golden scans, grouped by package family."""
    acc: dict[str, list[np.ndarray]] = {}
    for stack in golden_stacks:
        for c in brd.components:
            acc.setdefault(c.package, []).append(roi.extract_patch(stack, c, c.pkg))
    return {k: np.stack(v) for k, v in acc.items()}


def render_with(brd: B.Board, defects: dict[str, synth.Defect], seed: int = 11,
                **opts) -> np.ndarray:
    """Render one board with defects injected and no placement jitter.

    Jitter is disabled so a measured offset is the injected offset and nothing
    else, which keeps the assertions tight enough to catch a regression.
    """
    return synth.render(brd, defects=defects,
                        opts=synth.RenderOpts(seed=seed, place_sigma_um=0.0, **opts))
